"""Render evaluation summaries as Markdown, and refresh the README table from them.

Usage:
    uv run python -m rag.eval.report                  # README table from the latest run
    uv run python -m rag.eval.report --results results/20261113-160000

The README table sits between EVAL_START and EVAL_END markers and is replaced
wholesale, so evaluation numbers in the README are never typed by hand.
"""

import argparse
import json
from pathlib import Path

EVAL_START = "<!-- EVAL-TABLE:START (generated by python -m rag.eval.report; do not edit) -->"
EVAL_END = "<!-- EVAL-TABLE:END -->"


def pct(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.0f}%"


def num(x: float | None, digits: int = 2) -> str:
    return "–" if x is None else f"{x:.{digits}f}"


def ci_cell(ci: dict | None, as_pct: bool = True) -> str:
    if not ci or ci.get("mean") is None:
        return "–"
    f = pct if as_pct else num
    return f"{f(ci['mean'])} [{f(ci['low'])}–{f(ci['high'])}]"


def retrieval_table(report: dict) -> list[str]:
    lines = [
        "| Questions | n | hit@1 | hit@3 | hit@5 | hit@10 | MRR |",
        "|---|---|---|---|---|---|---|",
    ]
    groups = [("overall", report["overall"])] + list(report["by_type"].items())
    for name, s in groups:
        if s.get("n"):
            lines.append(
                f"| {name} | {s['n']} | {pct(s['hit@1'])} | {pct(s['hit@3'])} | "
                f"{pct(s['hit@5'])} | {pct(s['hit@10'])} | {num(s['mrr'])} |"
            )
    return lines


def headline_rows(summary: dict) -> list[str]:
    ci = summary["ci95"]
    ref = summary["refusals"]
    rows = [
        "| Metric | Value [95% CI] |",
        "|---|---|",
        f"| hit@5 (page level) | {ci_cell(ci['hit@5'])} |",
        f"| MRR@10 (page level) | {ci_cell(ci['mrr'], as_pct=False)} |",
        f"| refusal accuracy | {ci_cell(ci['refusal_accuracy'])} |",
        f"| false-refusal rate | {pct(ref['false_refusal_rate'])} |",
        f"| unanswerable caught | {pct(ref['unanswerable_caught_rate'])} |",
        f"| citation validity | {pct(summary['citation_validity']['rate'])} "
        f"(of {summary['citation_validity']['n_citations']}) |",
        f"| gold page in LLM context | {pct(summary.get('gold_in_context_rate'))} |",
        f"| citation correctness (cites a gold page) | "
        f"{pct(summary['citation_correctness']['rate'])} |",
    ]
    for judge, f in sorted(summary.get("faithfulness", {}).items()):
        rows.append(f"| faithfulness, supported (judge: {judge}) | {ci_cell(f['ci95'])} |")
    return rows


def config_line(config: dict) -> str:
    return (
        f"backend `{config['backend']}` (model `{config['llm_model']}`), k={config['k']}, "
        f"per-doc={config['per_doc']}, threshold={config['min_score']}, "
        f"split `{config.get('split')}`, "
        f"embedding `{config['embedding_model']}`, chunks {config['chunk_size_words']}/"
        f"{config['overlap_words']} words, created {config['created_at']}"
    )


def caveats(summary: dict) -> list[str]:
    notes = [
        f"> {summary['n_questions']} questions. Intervals are 95% bootstrap CIs (1000 resamples, "
        "seed 0); with this few questions they are wide, so small differences are not meaningful."
    ]
    if summary["includes_unverified"]:
        notes.append("> **Includes unverified (LLM-drafted) questions: not a reportable result.**")
    if summary.get("n_questions") and summary["refusals"]["n_unanswerable"] == 0:
        notes.append("> No unanswerable questions in this run: refusal metrics are one-sided.")
    return notes


def render_summary(summary: dict, config: dict) -> str:
    cost = summary["cost_usd"]
    lines = [
        "# Evaluation summary",
        "",
        config_line(config),
        "",
        *caveats(summary),
        "",
        "## Headline metrics",
        "",
        *headline_rows(summary),
        "",
        "## Retrieval, page level (right document and page)",
        "",
        *retrieval_table(summary["retrieval_page"]),
        "",
        "## Retrieval, document level (right document, any page)",
        "",
        *retrieval_table(summary["retrieval_doc"]),
        "",
        "## Usage",
        "",
        f"tokens in/out: {summary['tokens']['input']}/{summary['tokens']['output']}, "
        f"estimated cost: {'–' if cost is None else f'${cost:.4f}'}, "
        f"mean latency: {num(summary['mean_latency_s'])} s",
        "",
    ]
    return "\n".join(lines)


def readme_table(summary: dict, config: dict, run_name: str) -> str:
    return "\n".join(
        [
            EVAL_START,
            f"Run `results/{run_name}`: {config_line(config)}",
            "",
            *caveats(summary),
            "",
            *headline_rows(summary),
            EVAL_END,
        ]
    )


def replace_block(text: str, block: str) -> str:
    """Replace the marked block in `text`; raise if the markers are missing."""
    start, end = text.find(EVAL_START), text.find(EVAL_END)
    if start == -1 or end == -1 or end < start:
        raise ValueError("README is missing the EVAL-TABLE markers")
    return text[:start] + block + text[end + len(EVAL_END) :]


def latest_eval_run(results_dir: Path) -> Path:
    runs = sorted(
        p.parent
        for p in results_dir.glob("*/summary.json")
        if json.loads(p.read_text(encoding="utf-8")).get("kind") == "eval"
    )
    if not runs:
        raise SystemExit(f"No evaluation runs in {results_dir}. Run: python -m rag.eval.run")
    return runs[-1]


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Refresh the README evaluation table.")
    parser.add_argument("--results", type=Path, default=None, help="a results/<run> directory")
    parser.add_argument("--readme", type=Path, default=Path("README.md"))
    args = parser.parse_args(argv)

    run = args.results or latest_eval_run(Path("results"))
    summary = json.loads((run / "summary.json").read_text(encoding="utf-8"))
    config = json.loads((run / "config.json").read_text(encoding="utf-8"))
    readme = args.readme.read_text(encoding="utf-8")
    args.readme.write_text(
        replace_block(readme, readme_table(summary, config, run.name)), encoding="utf-8"
    )
    print(f"README evaluation table updated from {run}")


if __name__ == "__main__":
    main()
